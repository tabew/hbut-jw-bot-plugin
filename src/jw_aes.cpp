std::string aes128_cbc_encrypt(const std::string& key16, const std::string& iv16,
                               const std::string& plain) {
    uint8_t key[16] = {0};
    uint8_t iv[16] = {0};
    memcpy(key, key16.data(), key16.size() < 16 ? key16.size() : 16);
    memcpy(iv, iv16.data(), iv16.size() < 16 ? iv16.size() : 16);

    AesKey ks;
    expand_key(key, ks);

    std::string data = plain;
    // PKCS7 填充
    uint8_t pad = (uint8_t)(16 - (data.size() % 16));
    data.append(pad, (char)pad);

    std::string out;
    out.resize(data.size());
    uint8_t prev[16];
    memcpy(prev, iv, 16);
    for (size_t off = 0; off < data.size(); off += 16) {
        uint8_t block[16];
        memcpy(block, data.data() + off, 16);
        for (int i = 0; i < 16; ++i) block[i] ^= prev[i];
        encrypt_block(ks, block);
        memcpy(prev, block, 16);
        memcpy(&out[off], block, 16);
    }
    return out;
}

std::string cas_encrypt_password(const std::string& password, const std::string& salt) {
    std::string key = salt;
    if (key.size() != 16) {
        // 盐长度异常时补齐/截断，避免直接崩溃；服务端会拒掉，这里只是不崩
        key.resize(16, '0');
    }
    std::string iv = random_string(16);
    std::string plain = random_string(64) + password;
    return base64_encode(aes128_cbc_encrypt(key, iv, plain));
}

