const uint8_t kRcon[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

inline uint8_t xtime(uint8_t x) { return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0x00)); }

inline uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; ++i) {
        if (b & 1) p ^= a;
        uint8_t hi = (uint8_t)(a & 0x80);
        a = (uint8_t)(a << 1);
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

struct AesKey {
    uint8_t round[176];
};

void expand_key(const uint8_t key[16], AesKey& ks) {
    memcpy(ks.round, key, 16);
    uint8_t tmp[4];
    for (int i = 4; i < 44; ++i) {
        memcpy(tmp, ks.round + (i - 1) * 4, 4);
        if (i % 4 == 0) {
            // RotWord + SubWord + Rcon
            uint8_t t0 = tmp[0];
            tmp[0] = (uint8_t)(kSbox[tmp[1]] ^ kRcon[i / 4]);
            tmp[1] = kSbox[tmp[2]];
            tmp[2] = kSbox[tmp[3]];
            tmp[3] = kSbox[t0];
        }
        for (int j = 0; j < 4; ++j) {
            ks.round[i * 4 + j] = (uint8_t)(ks.round[(i - 4) * 4 + j] ^ tmp[j]);
        }
    }
}

void encrypt_block(const AesKey& ks, uint8_t block[16]) {
    // AddRoundKey
    for (int i = 0; i < 16; ++i) block[i] ^= ks.round[i];

    for (int round = 1; round <= 10; ++round) {
        // SubBytes
        for (int i = 0; i < 16; ++i) block[i] = kSbox[block[i]];
        // ShiftRows（state 为列主序：block[c*4 + r]）
        uint8_t t[16];
        memcpy(t, block, 16);
        for (int r = 0; r < 4; ++r) {
            for (int c = 0; c < 4; ++c) {
                block[c * 4 + r] = t[((c + r) % 4) * 4 + r];
            }
        }
        // MixColumns（最后一轮不做）
        if (round != 10) {
            for (int c = 0; c < 4; ++c) {
                uint8_t* col = block + c * 4;
                uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
                col[0] = (uint8_t)(gmul(a0, 2) ^ gmul(a1, 3) ^ a2 ^ a3);
                col[1] = (uint8_t)(a0 ^ gmul(a1, 2) ^ gmul(a2, 3) ^ a3);
                col[2] = (uint8_t)(a0 ^ a1 ^ gmul(a2, 2) ^ gmul(a3, 3));
                col[3] = (uint8_t)(gmul(a0, 3) ^ a1 ^ a2 ^ gmul(a3, 2));
            }
        }
        // AddRoundKey
        for (int i = 0; i < 16; ++i) block[i] ^= ks.round[round * 16 + i];
    }
}

